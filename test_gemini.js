const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

async function askGemini(keywords) {
  if (keywords.length === 0) {
    console.log("❌ 입력된 키워드가 없습니다. 다시 시작합니다.\n");
    return;
  }

  const combinedPrompt = `
[시스템 지시사항]
${systemPrompt}

[추출 가능 기준 단어 리스트]
${referenceWords.join(", ")}

[사용자가 입력한 검색 키워드]
${keywords.join(", ")}
`;

  try {
    const response = await fetch(URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: combinedPrompt }] }]
      })
    });

    const data = await response.json();
    if (data.error) throw new Error(data.error.message);

    const aiResponseText = data.candidates[0].content.parts[0].text;
    console.log(`\n💡 [AI 결과] (요청 키워드: ${keywords.join(", ")}) ----------------`);
    console.log(aiResponseText);
    console.log("------------------------------------------\n");
  } catch (error) {
    console.error("\n❌ 에러 발생:", error.message, "\n");
  }
}

function promptKeywords() {
  if (API_KEY === '여기에_발급받은_API_KEY를_넣어주세요') {
    console.error("\n❌ 오류: 스크립트 3번째 줄에 API_KEY를 먼저 입력해주세요!\n");
    rl.close();
    return;
  }

  const collectedKeywords = [];

  const askNext = (step) => {
    rl.question(`${step}번째 키워드를 입력하세요 (넘어가고 바로 AI에게 보내려면 x / 종료하려면 q): `, async (input) => {
      const val = input.trim();
      
      if (val.toLowerCase() === 'q') {
        rl.close();
        return;
      }

      if (val.toLowerCase() === 'x') {
        console.log("\n요청 중... 잠시만 기다려주세요⏳");
        await askGemini(collectedKeywords);
        promptKeywords(); // 테스트 완료 후 다시 처음으로
        return;
      }

      if (val !== '') {
        collectedKeywords.push(val);
      }

      if (step < 3) {
        askNext(step + 1);
      } else {
        console.log("\n요청 중... 잠시만 기다려주세요⏳");
        await askGemini(collectedKeywords);
        promptKeywords();
      }
    });
  };

  askNext(1);
}

